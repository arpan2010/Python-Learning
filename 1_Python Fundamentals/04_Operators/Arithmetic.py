a = 15
b = 4
print("Addition : ", a + b)
print("Subtraction : ", a - b)
print("Multiplication : ", a * b)
print("Division : ", a / b)
print("Floor Division : ", a // b)              #removes decimal number
print("Modulus : ", a % b)
print("Exponentiation : ", a ** b)              #15*15*15*15 (15 raise to the power 4)
